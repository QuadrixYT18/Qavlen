package de.quadrixyt.qavlen.storage

import java.util.UUID
import kotlin.test.AfterTest
import kotlin.test.Test
import kotlin.test.assertContentEquals
import kotlin.test.assertEquals
import kotlin.test.assertFailsWith
import kotlin.test.assertNull
import kotlin.test.assertTrue

class DatabaseTest {
    private var blocked = false
    private val testThread = Thread.currentThread()
    private val database = Database.builder("jdbc:h2:mem:${UUID.randomUUID()};MODE=PostgreSQL;DB_CLOSE_DELAY=-1")
        .poolSize(2)
        .forbidBlockingWhen { blocked && Thread.currentThread() == testThread }
        .connect()

    private val migrations = Migrations(database)
        .add(1, "create players", "CREATE TABLE players (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(64) NOT NULL UNIQUE, coins INT NOT NULL)")
        .add(2, "add rank", "ALTER TABLE players ADD COLUMN player_rank VARCHAR(16) DEFAULT 'MEMBER' NOT NULL")

    enum class Rank { MEMBER, ADMIN }

    @AfterTest
    fun close() = database.close()

    @Test
    fun `migrations run once and detect edits`() {
        assertEquals(listOf(1, 2), migrations.migrate())
        assertEquals(emptyList(), migrations.migrate())

        val edited = Migrations(database)
            .add(1, "create players", "CREATE TABLE players (id INT)")
            .add(2, "add rank", "ALTER TABLE players ADD COLUMN player_rank VARCHAR(16) DEFAULT 'MEMBER' NOT NULL")
        assertFailsWith<IllegalStateException> { edited.migrate() }
    }

    @Test
    fun `queries bind parameters safely`() {
        migrations.migrate()
        val id = database.insert("INSERT INTO players (name, coins, player_rank) VALUES (?, ?, ?)", "Alex", 10, Rank.ADMIN)
        database.batch("INSERT INTO players (name, coins) VALUES (?, ?)", listOf(listOf("Sam", 5), listOf("Robert'); DROP TABLE players;--", 1)))

        val names = database.query("SELECT name FROM players ORDER BY id", { it.getString(1) })
        assertEquals(listOf("Alex", "Sam", "Robert'); DROP TABLE players;--"), names)
        assertEquals("ADMIN", database.queryFirst("SELECT player_rank FROM players WHERE id = ?", { it.getString(1) }, id))
        assertNull(database.queryFirst("SELECT name FROM players WHERE name = ?", { it.getString(1) }, "nobody"))
    }

    @Test
    fun `transactions roll back on failure`() {
        migrations.migrate()
        database.update("INSERT INTO players (name, coins) VALUES (?, ?)", "Alex", 10)

        assertFailsWith<IllegalStateException> {
            database.transaction { session ->
                session.update("UPDATE players SET coins = coins - 5 WHERE name = ?", "Alex")
                error("payment failed")
            }
        }
        assertEquals(10, database.queryFirst("SELECT coins FROM players WHERE name = ?", { it.getInt(1) }, "Alex"))
        assertFailsWith<DatabaseException> { database.update("INSERT INTO players (name, coins) VALUES (?, ?)", "Alex", 1) }
    }

    @Test
    fun `async calls run off the guarded thread`() {
        migrations.migrate()
        blocked = true

        assertFailsWith<IllegalStateException> { database.update("DELETE FROM players") }
        assertEquals(
            1,
            database.insertAsync("INSERT INTO players (name, coins) VALUES (?, ?)", "Async", 3).thenCompose {
                database.queryAsync("SELECT coins FROM players", { row -> row.getInt(1) })
            }.join().single().let { if (it == 3) 1 else 0 },
        )
        assertContentEquals(intArrayOf(1, 1), database.batchAsync("UPDATE players SET coins = ? WHERE name = ?", listOf(listOf(4, "Async"), listOf(5, "Async"))).join())
    }

    @Test
    fun `slow statements are cancelled after the query timeout`() {
        Database.builder("jdbc:h2:mem:${UUID.randomUUID()}").queryTimeout(java.time.Duration.ofSeconds(1)).connect().use { slow ->
            val started = System.nanoTime()

            assertFailsWith<DatabaseException> {
                slow.query("SELECT SUM(a.X * b.X) FROM SYSTEM_RANGE(1, 100000) a, SYSTEM_RANGE(1, 100000) b", { it.getLong(1) })
            }

            assertTrue(System.nanoTime() - started < java.util.concurrent.TimeUnit.SECONDS.toNanos(10))
        }
    }

    @Test
    fun `async calls after close fail instead of throwing`() {
        val closed = Database.builder("jdbc:h2:mem:${UUID.randomUUID()}").connect()
        closed.close()

        val failure = assertFailsWith<java.util.concurrent.CompletionException> { closed.updateAsync("SELECT 1").join() }
        assertTrue(failure.cause is IllegalStateException)
    }

    @Test
    fun `connects from settings and hides the password`() {
        val settings = DatabaseSettings(url = "jdbc:h2:mem:${UUID.randomUUID()}", username = "sa", password = "secret", poolSize = 2)

        Database.connect(settings).use { database -> assertEquals(1, database.queryFirst("SELECT 1", { it.getInt(1) })) }

        assertTrue("secret" !in settings.toString())
        assertEquals("jdbc:postgresql://db:5432/game", DatabaseSettings(DatabaseType.POSTGRESQL, "db", database = "game").jdbcUrl)
        assertFailsWith<IllegalArgumentException> { Database.builder(settings.copy(poolSize = 0)) }
    }
}
